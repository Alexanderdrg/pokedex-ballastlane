CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(30)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(10)  NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE local_pokemon (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pokeapi_id     INTEGER      NOT NULL UNIQUE,
    name           VARCHAR(60)  NOT NULL,
    image_url      VARCHAR(300),
    sprite_url     VARCHAR(300),
    category       VARCHAR(60),
    height_m       DOUBLE PRECISION NOT NULL,
    weight_kg      DOUBLE PRECISION NOT NULL,
    localized_name VARCHAR(60),
    region         VARCHAR(20),
    notes          VARCHAR(500),
    synced_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    version        BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE local_pokemon_type (
    pokemon_id BIGINT      NOT NULL REFERENCES local_pokemon (id) ON DELETE CASCADE,
    position   INTEGER     NOT NULL,
    type       VARCHAR(30) NOT NULL,
    PRIMARY KEY (pokemon_id, position)
);

CREATE TABLE local_pokemon_ability (
    pokemon_id BIGINT      NOT NULL REFERENCES local_pokemon (id) ON DELETE CASCADE,
    position   INTEGER     NOT NULL,
    ability    VARCHAR(60) NOT NULL,
    PRIMARY KEY (pokemon_id, position)
);

CREATE TABLE local_pokemon_tag (
    pokemon_id BIGINT      NOT NULL REFERENCES local_pokemon (id) ON DELETE CASCADE,
    tag        VARCHAR(20) NOT NULL,
    PRIMARY KEY (pokemon_id, tag)
);

CREATE INDEX idx_local_pokemon_name ON local_pokemon (name);
